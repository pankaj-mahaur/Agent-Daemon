#!/usr/bin/env node
// L0 spike S-HISTORY (docs/plans/mcp-platform 06 §1).
//
//   node tools/spikes/s-history.mjs bench [--sessions 2000] [--entries 60]
//     Generates synthetic Claude Code transcripts and Codex rollouts in a temp
//     folder (shapes from the real 2.1.314 / 0.164.0 captures), then times a
//     streaming read that keeps only typed user prompts. Prints p50 timings
//     for a plain JSON.parse-every-line reader and a substring-prefilter one.
//
//   node tools/spikes/s-history.mjs sample <in.jsonl> <out.jsonl>
//     Shape-preserving copy of a transcript captured in a temp home: every
//     string longer than 160 chars is cut (no vendor prompts or tool output
//     land in a fixture), then the account name and checkout path are scrubbed.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import readline from "node:readline";
import { scrub } from "./s-hooks/sanitize.mjs";

const arg = (n, d) => (process.argv.includes(n) ? process.argv[process.argv.indexOf(n) + 1] : d);

if (process.argv[2] === "sample") {
  const [src, dest] = process.argv.slice(3);
  const cut = (v) => (typeof v === "string" ? (v.length > 160 ? v.slice(0, 160) + "…[cut]" : v) : Array.isArray(v) ? v.map(cut) : v && typeof v === "object" ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, cut(x)])) : v);
  // Instruction attachments carry whole CLAUDE.md files (Claude Code walks
  // parent folders, so a temp project under the profile picks up the user's
  // own); keep only their type and drop the content.
  const strip = (e) => {
    if (e.attachment?.type === "instructions") e.attachment.files = (e.attachment.files ?? []).map((f) => ({ type: f.type, path: "<dropped>", content: "<dropped>" }));
    return e;
  };
  const lines = fs.readFileSync(src, "utf8").trim().split("\n").map((l) => JSON.stringify(cut(strip(JSON.parse(l)))));
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, scrub(lines.join("\n")) + "\n");
  process.exit(0);
}

const SESSIONS = Number(arg("--sessions", 2000));
const ENTRIES = Number(arg("--entries", 60));
const root = fs.mkdtempSync(path.join(os.tmpdir(), "s-history-"));
const pad = (n) => "x".repeat(n);
const uuid = (i, j) => `00000000-0000-4000-8000-${String(i).padStart(6, "0")}${String(j).padStart(6, "0")}`;

// Claude Code: one JSONL per session under projects/<slug>/; subagent files
// under <session>/subagents/; entries carry isMeta / isSidechain /
// isCompactSummary / promptSource, and tool results come back as user entries.
function claudeSession(i) {
  const out = [];
  let parent = null;
  const push = (e) => { const u = uuid(i, out.length); out.push(JSON.stringify({ parentUuid: parent, isSidechain: false, userType: "external", cwd: "/work/app", sessionId: `s${i}`, version: "2.1.314", gitBranch: "main", uuid: u, timestamp: new Date(Date.UTC(2026, 9, 1 + (i % 30))).toISOString(), ...e })); parent = u; };
  push({ type: "user", isMeta: true, message: { role: "user", content: "<local-command-caveat>Caveat: generated by a local command</local-command-caveat>" } });
  for (let j = 0; out.length < ENTRIES; j++) {
    push({ type: "user", promptSource: j % 7 === 6 ? "system" : "user", message: { role: "user", content: j % 5 === 0 ? `no, use pnpm here, never npm (${i}.${j})` : `please refactor module ${j} of project ${i % 40}` } });
    push({ type: "assistant", message: { role: "assistant", content: [{ type: "tool_use", id: `t${i}_${j}`, name: "Bash", input: { command: "pnpm test" } }] } });
    push({ type: "user", toolUseResult: { stdout: pad(1500) }, message: { role: "user", content: [{ type: "tool_result", tool_use_id: `t${i}_${j}`, content: pad(1500) }] } });
    push({ type: "assistant", message: { role: "assistant", content: [{ type: "text", text: pad(600) }] } });
    if (j === 3 && i % 10 === 0) push({ type: "user", isCompactSummary: true, message: { role: "user", content: `This session is being continued from a previous conversation. ${pad(4000)}` } });
  }
  return out.join("\n") + "\n";
}

// Codex: sessions/YYYY/MM/DD/rollout-*.jsonl; typed text is a response_item
// user message; injected context is a user message too (<environment_context>).
function codexRollout(i) {
  const out = [];
  const line = (type, payload) => out.push(JSON.stringify({ timestamp: new Date(Date.UTC(2026, 9, 1 + (i % 30))).toISOString(), type, payload }));
  line("session_meta", { id: `c${i}`, cwd: "/work/app", originator: "codex_cli_rs", cli_version: "0.164.0", source: "cli", base_instructions: { text: pad(8000) } });
  line("response_item", { type: "message", role: "developer", content: [{ type: "input_text", text: pad(3000) }] });
  line("response_item", { type: "message", role: "user", content: [{ type: "input_text", text: `<environment_context>\n  <cwd>/work/app</cwd>\n</environment_context>` }] });
  for (let j = 0; out.length < ENTRIES; j++) {
    line("turn_context", { cwd: "/work/app", approval_policy: "on-request", sandbox_policy: { type: "workspace-write" }, model: "gpt-5" });
    line("response_item", { type: "message", role: "user", content: [{ type: "input_text", text: j % 5 === 0 ? `stop using npm, we use pnpm (${i}.${j})` : `fix test ${j}` }] });
    line("response_item", { type: "function_call", name: "exec_command", arguments: JSON.stringify({ cmd: "pnpm test" }), call_id: `c${i}_${j}` });
    line("response_item", { type: "function_call_output", call_id: `c${i}_${j}`, output: pad(1500) });
    line("response_item", { type: "message", role: "assistant", content: [{ type: "output_text", text: pad(600) }] });
    line("event_msg", { type: "token_count", info: null });
  }
  return out.join("\n") + "\n";
}

const t0 = Date.now();
const claudeDir = path.join(root, "claude", "projects", "-work-app");
const codexDir = path.join(root, "codex", "sessions", "2026", "10", "01");
fs.mkdirSync(claudeDir, { recursive: true });
fs.mkdirSync(codexDir, { recursive: true });
let bytes = 0;
for (let i = 0; i < SESSIONS; i++) {
  const c = claudeSession(i);
  const x = codexRollout(i);
  bytes += c.length + x.length;
  fs.writeFileSync(path.join(claudeDir, `s${i}.jsonl`), c);
  fs.writeFileSync(path.join(codexDir, `rollout-2026-10-01T00-00-00-c${i}.jsonl`), x);
}
const genMs = Date.now() - t0;

const isTypedClaude = (e) => e.type === "user" && !e.isMeta && !e.isSidechain && !e.isCompactSummary && e.promptSource !== "system" && (typeof e.message?.content === "string" || e.message?.content?.every?.((b) => b.type === "text"));
const isTypedCodex = (e) => e.type === "response_item" && e.payload?.type === "message" && e.payload.role === "user" && !/^<(environment_context|user_instructions|turn_aborted)/.test(e.payload.content?.[0]?.text ?? "");

async function readAll(dir, keep, prefilter) {
  let typed = 0;
  let lines = 0;
  const seen = new Set();
  for (const f of fs.readdirSync(dir)) {
    const rl = readline.createInterface({ input: fs.createReadStream(path.join(dir, f), { encoding: "utf8" }), crlfDelay: Infinity });
    for await (const line of rl) {
      lines++;
      if (prefilter && !prefilter(line)) continue;
      const e = JSON.parse(line);
      if (!keep(e)) continue;
      const id = e.uuid ?? `${f}:${lines}`;
      if (seen.has(id)) continue; // forked / resumed copies share uuids
      seen.add(id);
      typed++;
    }
  }
  return { typed, lines };
}

const results = {};
for (const [name, dir, keep, pre] of [
  ["claude: parse every line", claudeDir, isTypedClaude, null],
  ["claude: prefilter '\"type\":\"user\"' && no tool_result", claudeDir, isTypedClaude, (l) => l.includes('"type":"user"') && !l.includes('"tool_result"')],
  ["codex: parse every line", codexDir, isTypedCodex, null],
  ["codex: prefilter '\"role\":\"user\"'", codexDir, isTypedCodex, (l) => l.includes('"role":"user"')],
]) {
  const ms = [];
  let r;
  for (let k = 0; k < 3; k++) {
    const t = Date.now();
    r = await readAll(dir, keep, pre);
    ms.push(Date.now() - t);
  }
  ms.sort((a, b) => a - b);
  results[name] = { ms: ms[1], ...r };
}
const report = { spike: "S-HISTORY", os: `${os.platform()} ${os.release()}`, node: process.version, sessionsPerHost: SESSIONS, entriesPerSession: ENTRIES, megabytes: Math.round(bytes / 1e6), generateMs: genMs, results };
console.log(JSON.stringify(report, null, 1));
if (arg("--json")) fs.writeFileSync(arg("--json"), JSON.stringify(report, null, 2) + "\n");
fs.rmSync(root, { recursive: true, force: true });
