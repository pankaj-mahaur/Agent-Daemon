#!/usr/bin/env node
// Quick-try links for the memory server (P5.6), pinned to the exact package
// version: an unpinned `npx agent-daemon-memory` would start whatever npm
// serves that day.
//
//   node runtime/scripts/memory-deeplinks.mjs           print them
//   node runtime/scripts/memory-deeplinks.mjs --write   refresh the block in docs/memory/install.md
//
// The installer stays the daily route (no npx start-up per session, no network).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const PKG = path.join(REPO, "packages", "agent-daemon-memory", "package.json");
export const INSTALL_DOC = path.join(REPO, "docs", "memory", "install.md");
export const BEGIN = "<!-- quick-try:begin (generated by runtime/scripts/memory-deeplinks.mjs) -->";
export const END = "<!-- quick-try:end -->";

/** The npx launch of one host's server, pinned. */
export function npxServer(name, version, host, extra = []) {
  return { command: "npx", args: ["-y", `${name}@${version}`, "serve", "--host", host, "--capture", "tools", ...extra] };
}

/** Cursor's MCP install deeplink: the server config as base64 JSON. */
export function cursorDeeplink(name, version) {
  const config = Buffer.from(JSON.stringify(npxServer(name, version, "cursor", ["--project", "${workspaceFolder}"]))).toString("base64");
  return `cursor://anysphere.cursor-deeplink/mcp/install?name=${encodeURIComponent(name)}&config=${encodeURIComponent(config)}`;
}

/** VS Code's `code --add-mcp` argument. */
export function vscodeAddMcp(name, version) {
  return JSON.stringify({ name, type: "stdio", ...npxServer(name, version, "vscode") });
}

export function quickTryBlock({ name, version }) {
  return [
    BEGIN,
    "",
    `To try memory without installing it (each session starts \`${name}@${version}\` through npx, which needs the network the first time):`,
    "",
    "- **Cursor:** paste this link into your browser's address bar (Cursor binds the server to the open folder):",
    "",
    "  ```text",
    `  ${cursorDeeplink(name, version)}`,
    "  ```",
    "",
    "- **VS Code** (VS Code starts the server in the open folder; on Windows, run it from Git Bash: Windows PowerShell 5 strips the inner quotes):",
    "",
    "  ```bash",
    `  code --add-mcp '${vscodeAddMcp(name, version)}'`,
    "  ```",
    "",
    "For daily use, run the installer instead: it starts the server directly, with no npx and no network.",
    "",
    END,
  ].join("\n");
}

const pkg = () => JSON.parse(fs.readFileSync(PKG, "utf8"));

/** The install doc with its quick-try block replaced by the current one. */
export function withQuickTry(doc, info = pkg()) {
  const s = doc.indexOf(BEGIN);
  const e = doc.indexOf(END);
  if (s < 0 || e < s) throw new Error("docs/memory/install.md has no quick-try block markers");
  return doc.slice(0, s) + quickTryBlock(info) + doc.slice(e + END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const info = pkg();
  if (process.argv.includes("--write")) {
    const doc = fs.readFileSync(INSTALL_DOC, "utf8");
    const crlf = doc.includes("\r\n");
    const next = withQuickTry(doc.replace(/\r\n/g, "\n"), info);
    fs.writeFileSync(INSTALL_DOC, crlf ? next.replace(/\n/g, "\r\n") : next);
    console.log(`quick-try block refreshed for ${info.name}@${info.version}`);
  } else {
    console.log(cursorDeeplink(info.name, info.version));
    console.log(`code --add-mcp '${vscodeAddMcp(info.name, info.version)}'`);
  }
}
