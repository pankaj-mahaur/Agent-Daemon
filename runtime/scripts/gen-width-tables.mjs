#!/usr/bin/env node
// Generates src/tui/terminal/width-table.mjs: the code point ranges whose East
// Asian Width is W (wide) or F (fullwidth), i.e. two terminal cells.
//
// JavaScript regexes have no East_Asian_Width property, so this one table is
// vendored. Zero-width and emoji rules come from regex properties at runtime
// (see width.mjs). Ambiguous (A) stays 1 cell, as in Codex and most terminals.
//
// Usage:
//   node scripts/gen-width-tables.mjs            # the pinned DEFAULT_VERSION
//   node scripts/gen-width-tables.mjs 16.0.0
//   node scripts/gen-width-tables.mjs --file EastAsianWidth.txt --version 16.0.0

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "..", "src", "tui", "terminal", "width-table.mjs");
// Pinned so the output is reproducible; bump it deliberately (and re-run the tests).
const DEFAULT_VERSION = "16.0.0";

function arg(name) {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : undefined;
}

function normalizeVersion(v) {
  const parts = String(v).split(".");
  while (parts.length < 3) parts.push("0");
  return parts.slice(0, 3).join(".");
}

export function parseEastAsianWidth(text, version) {
  const header = /EastAsianWidth-(\d+\.\d+\.\d+)\.txt/.exec(text.slice(0, 200));
  if (version && header && header[1] !== version) {
    throw new Error(`file is EastAsianWidth-${header[1]}, expected ${version}`);
  }
  const ranges = [];
  for (const raw of text.split("\n")) {
    const line = raw.replace(/#.*/, "").trim();
    if (!line) continue;
    const [cps, prop] = line.split(";").map((s) => s.trim());
    if (prop !== "W" && prop !== "F") continue;
    const m = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?$/i.exec(cps);
    if (!m) throw new Error(`malformed code point range: ${raw.trim()}`);
    ranges.push([parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16)]);
  }
  ranges.sort((x, y) => x[0] - y[0]);
  const merged = [];
  for (const r of ranges) {
    const last = merged[merged.length - 1];
    if (last && r[0] <= last[1] + 1) last[1] = Math.max(last[1], r[1]);
    else merged.push([r[0], r[1]]);
  }
  return merged;
}

export function renderTable(ranges, version) {
  const hex = (n) => "0x" + n.toString(16).toUpperCase();
  const flat = ranges.map(([a, b]) => `${hex(a)},${hex(b)}`);
  const rows = [];
  for (let i = 0; i < flat.length; i += 6) rows.push("  " + flat.slice(i, i + 6).join(", ") + ",");
  return `// Generated by scripts/gen-width-tables.mjs from Unicode ${version} EastAsianWidth.txt.
// Do not edit by hand. Flat [start, end, start, end, ...] pairs, sorted, merged.

export const UNICODE_VERSION = "${version}";

export const WIDE = new Uint32Array([
${rows.join("\n")}
]);
`;
}

async function main() {
  const file = arg("--file");
  const positional = process.argv[2] && !process.argv[2].startsWith("--") ? process.argv[2] : undefined;
  const version = normalizeVersion(arg("--version") ?? positional ?? DEFAULT_VERSION);
  let text;
  if (file) {
    text = fs.readFileSync(file, "utf8");
  } else {
    const url = `https://www.unicode.org/Public/${version}/ucd/EastAsianWidth.txt`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`GET ${url}: HTTP ${res.status}`);
    text = await res.text();
  }
  const ranges = parseEastAsianWidth(text, version);
  if (ranges.length < 50) throw new Error(`only ${ranges.length} wide ranges parsed; wrong file?`);
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, renderTable(ranges, version));
  console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${ranges.length} ranges, Unicode ${version}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
