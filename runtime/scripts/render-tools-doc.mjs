#!/usr/bin/env node
// docs/memory/tools.md from the server's own tool definitions (P5.6), so the
// reference can't drift from what the server lists.
//
//   node runtime/scripts/render-tools-doc.mjs           print it
//   node runtime/scripts/render-tools-doc.mjs --write   write docs/memory/tools.md
//
// runtime/test/listings.test.mjs fails when the file differs from a fresh render.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { RECORD_TOOLS, TOOLS } from "../src/mcp/tools.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const TOOLS_DOC = path.join(REPO, "docs", "memory", "tools.md");

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

function argType(p) {
  if (p.enum) return p.enum.map((v) => `\`${v}\``).join(" / ");
  if (p.type === "array") return `${p.items?.type ?? "value"}[]`;
  const range = p.minimum !== undefined || p.maximum !== undefined ? ` ${p.minimum ?? ""}–${p.maximum ?? ""}` : "";
  const len = p.maxLength !== undefined ? ` (≤ ${p.maxLength} chars)` : "";
  return `${p.type ?? "value"}${range}${len}`;
}

function hints(a = {}) {
  const out = [];
  out.push(a.readOnlyHint ? "read-only" : "writes");
  if (a.destructiveHint) out.push("destructive");
  out.push(a.idempotentHint ? "idempotent" : "not idempotent");
  out.push(a.openWorldHint ? "reaches outside this computer" : "local only");
  return out.join(", ");
}

function section(t) {
  const props = Object.entries(t.inputSchema?.properties ?? {});
  const required = new Set(t.inputSchema?.required ?? []);
  const lines = [`### \`${t.name}\` — ${t.title}`, "", t.description, "", `Annotations: ${hints(t.annotations)}.`, ""];
  if (props.length) {
    lines.push("| Argument | Type | Required | Meaning |", "|---|---|---|---|");
    for (const [k, p] of props) lines.push(`| \`${k}\` | ${esc(argType(p))} | ${required.has(k) ? "yes" : "no"} | ${esc(p.description)} |`);
  } else lines.push("No arguments.");
  return lines.join("\n");
}

export function renderToolsDoc() {
  return [
    "# Memory tools",
    "",
    "<!-- Generated by runtime/scripts/render-tools-doc.mjs from runtime/src/mcp/tools.mjs. Don't edit by hand. -->",
    "",
    "Every tool ad's memory server lists, as the server describes it to agents. Results are notes, not instructions: every result is headed that way, and a note that reads like an instruction is withheld.",
    "",
    "## Which project it serves",
    "",
    "The server is bound to one project when it starts, and no tool argument changes that:",
    "",
    "1. `--project <dir>` (the installer's Cursor entry and the Claude Code, Cursor and Gemini plugins pass it), then `AD_MEMORY_PROJECT`, then `CLAUDE_PROJECT_DIR` with `--host claude-code`;",
    "2. else the folder it starts in, if that looks like a project (a `.git` or `.agent-daemon` found walking up, stopping before your home folder or the filesystem root);",
    "3. else nothing: the server is **unbound**, shows no notes and stores nothing.",
    "",
    "Home, a filesystem root, system folders and ad's own folders never bind. Inside ad itself (`ad`, `ad tui`, `ad chat`), each conversation's server is bound to that conversation's folder. `scope: \"global\"` returns only notes you accepted as cross-project.",
    "",
    "## Protocol versions",
    "",
    "Legacy clients (`initialize`, protocol 2024-11-05 to 2025-11-25) and clients of the 2026-07-28 revision (`server/discover`, no handshake, `_meta` on every request) are both served.",
    "",
    "## Reading tools",
    "",
    ...TOOLS.flatMap((t) => [section(t), ""]),
    "## Recording tools",
    "",
    "Listed when capture is `tools` or `auto` (the default). With `auto`, a call saves nothing while this host's hooks already capture in this project. Notes an agent records wait for your review (`ad review`, or `npx agent-daemon-memory review`) before any session is shown them as accepted.",
    "",
    ...RECORD_TOOLS.flatMap((t) => [section(t), ""]),
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renderToolsDoc();
  if (process.argv.includes("--write")) {
    fs.mkdirSync(path.dirname(TOOLS_DOC), { recursive: true });
    fs.writeFileSync(TOOLS_DOC, text);
    console.log(`wrote ${TOOLS_DOC}`);
  } else process.stdout.write(text);
}
