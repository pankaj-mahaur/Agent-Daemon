#!/usr/bin/env node
// L4a perf gate: `ad mistakes` over 2,000 synthetic sessions per host in at
// most 60 s on Linux (recorded per OS in the plan).
//
//   node runtime/scripts/mistakes-perf.mjs [--sessions 2000] [--entries 60] [--json out.json]
//
// Generates Claude Code transcripts and Codex rollouts in a temp home (shapes
// from the L0 captures, about 240 MB at the defaults), then times the whole
// read: list, read and filter, classify, cluster, render. The temp home is
// removed afterwards.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { listSources, readPrompts } from "../src/mistakes/history.mjs";
import { buildReport, renderText } from "../src/mistakes/report.mjs";
import { claudeProjectSlug } from "../src/mistakes/history.mjs";

const arg = (n, d) => (process.argv.includes(n) ? process.argv[process.argv.indexOf(n) + 1] : d);
const SESSIONS = Number(arg("--sessions", 2000));
const ENTRIES = Number(arg("--entries", 60));
const LIMIT_MS = 60_000;

const root = fs.mkdtempSync(path.join(os.tmpdir(), "ad-mistakes-perf-"));
const home = path.join(root, "home");
const cwd = path.join(root, "work", "app");
fs.mkdirSync(path.join(cwd, ".git"), { recursive: true });
const pad = (n) => "x".repeat(n);
const uuid = (i, j) => `00000000-0000-4000-8000-${String(i).padStart(6, "0")}${String(j).padStart(6, "0")}`;
const day = (i) => new Date(Date.UTC(2026, 9, 1 + (i % 30))).toISOString();
const PROMPTS = ["no, use pnpm here, never npm", "please refactor the module", "stop adding comments to every function", "fix the failing test", "we use tabs, not spaces", "add a login page"];

function claudeSession(i) {
  const out = [];
  let parent = null;
  const push = (e) => {
    const u = uuid(i, out.length);
    out.push(JSON.stringify({ parentUuid: parent, isSidechain: false, userType: "external", cwd, sessionId: `s${i}`, version: "2.1.314", gitBranch: "main", uuid: u, timestamp: day(i), ...e }));
    parent = u;
  };
  push({ type: "user", isMeta: true, message: { role: "user", content: "<local-command-caveat>Caveat: generated by a local command</local-command-caveat>" } });
  for (let j = 0; out.length < ENTRIES; j++) {
    push({ type: "user", promptSource: j % 7 === 6 ? "system" : "user", message: { role: "user", content: `${PROMPTS[j % PROMPTS.length]} (${i}.${j})` } });
    push({ type: "assistant", message: { role: "assistant", content: [{ type: "tool_use", id: `t${i}_${j}`, name: "Bash", input: { command: "pnpm test" } }] } });
    push({ type: "user", toolUseResult: { stdout: pad(1500) }, message: { role: "user", content: [{ type: "tool_result", tool_use_id: `t${i}_${j}`, content: pad(1500) }] } });
    push({ type: "assistant", message: { role: "assistant", content: [{ type: "text", text: pad(600) }] } });
  }
  return out.join("\n") + "\n";
}

function codexRollout(i) {
  const out = [];
  const line = (type, payload) => out.push(JSON.stringify({ timestamp: day(i), type, payload }));
  line("session_meta", { id: `c${i}`, cwd, originator: "codex_cli_rs", cli_version: "0.164.0", source: "cli", base_instructions: { text: pad(8000) } });
  line("response_item", { type: "message", role: "developer", content: [{ type: "input_text", text: pad(3000) }] });
  line("response_item", { type: "message", role: "user", content: [{ type: "input_text", text: `<environment_context>\n  <cwd>${cwd}</cwd>\n</environment_context>` }] });
  for (let j = 0; out.length < ENTRIES; j++) {
    line("turn_context", { cwd, approval_policy: "on-request", model: "gpt-5" });
    line("response_item", { type: "message", id: `m${i}_${j}`, role: "user", content: [{ type: "input_text", text: `${PROMPTS[(j + 3) % PROMPTS.length]} (${i}.${j})` }] });
    line("response_item", { type: "function_call", name: "exec_command", arguments: JSON.stringify({ cmd: "pnpm test" }), call_id: `c${i}_${j}` });
    line("response_item", { type: "function_call_output", call_id: `c${i}_${j}`, output: pad(1500) });
    line("response_item", { type: "message", role: "assistant", content: [{ type: "output_text", text: pad(600) }] });
    line("event_msg", { type: "token_count", info: null });
  }
  return out.join("\n") + "\n";
}

const t0 = Date.now();
const claudeDir = path.join(home, ".claude", "projects", claudeProjectSlug(cwd));
const codexDir = path.join(home, ".codex", "sessions", "2026", "10", "01");
fs.mkdirSync(claudeDir, { recursive: true });
fs.mkdirSync(codexDir, { recursive: true });
let bytes = 0;
for (let i = 0; i < SESSIONS; i++) {
  const c = claudeSession(i);
  const x = codexRollout(i);
  bytes += c.length + x.length;
  fs.writeFileSync(path.join(claudeDir, `s${i}.jsonl`), c);
  fs.writeFileSync(path.join(codexDir, `rollout-2026-10-01T00-00-00-c${i}.jsonl`), x);
}
const generateMs = Date.now() - t0;

const t1 = Date.now();
const cpu0 = process.cpuUsage();
const sources = listSources({ env: {}, home, cwd });
const withCalls = !process.argv.includes("--no-calls");
const { prompts, stats, calls = [] } = readPrompts(sources, { calls: withCalls });
const readMs = Date.now() - t1;
// The rule split replays each top repeat's rule over every call, as `ad mistakes` does.
const report = buildReport({ prompts, calls: withCalls ? calls : null, sources, stats, now: Date.parse("2026-11-01T00:00:00Z"), redact: { home, names: [] } });
renderText(report);
const totalMs = Date.now() - t1;
// CPU time holds up on a busy machine, where wall-clock time doesn't.
const cpu = process.cpuUsage(cpu0);
const cpuMs = Math.round((cpu.user + cpu.system) / 1000);

const result = {
  os: `${os.platform()} ${os.release()}`,
  node: process.version,
  cpus: os.cpus().length,
  sessionsPerHost: SESSIONS,
  megabytes: Math.round(bytes / 1e6),
  generateMs,
  readMs,
  totalMs,
  cpuMs,
  prompts: report.prompts,
  corrections: report.corrections,
  calls: calls.length,
  split: report.split,
  pass: totalMs <= LIMIT_MS,
};
console.log(JSON.stringify(result, null, 1));
if (arg("--json")) fs.writeFileSync(arg("--json"), JSON.stringify(result, null, 2) + "\n");
fs.rmSync(root, { recursive: true, force: true });
process.exitCode = result.pass ? 0 : 1;
